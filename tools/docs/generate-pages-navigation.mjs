import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const repositoryRoot = path.resolve(scriptDirectory, '../..')
const docsRoot = path.join(repositoryRoot, 'docs')
const outputPath = path.join(docsRoot, '_sidebar.md')

async function collectMarkdownFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true })
  const files = await Promise.all(
    entries.map(async (entry) => {
      const absolutePath = path.join(directory, entry.name)
      if (entry.isDirectory()) return collectMarkdownFiles(absolutePath)
      if (!entry.isFile() || !entry.name.endsWith('.md')) return []
      if (absolutePath === outputPath) return []
      return [absolutePath]
    }),
  )
  return files.flat()
}

function humanize(value) {
  return value
    .replace(/\.md$/, '')
    .replace(/^\d+[a-z]?-/, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (character) => character.toUpperCase())
}

function escapeLabel(value) {
  return value.replace(/([\\[\]])/g, '\\$1')
}

async function readTitle(absolutePath) {
  const markdown = await fs.readFile(absolutePath, 'utf8')
  const heading = markdown.match(/^#\s+(.+)$/m)?.[1]?.trim()
  return heading || humanize(path.basename(absolutePath))
}

function createDirectoryNode() {
  return { directories: new Map(), files: [] }
}

function addToTree(root, document) {
  const segments = document.relativePath.split('/')
  const fileName = segments.pop()
  let current = root

  for (const segment of segments) {
    if (!current.directories.has(segment)) {
      current.directories.set(segment, createDirectoryNode())
    }
    current = current.directories.get(segment)
  }

  current.files.push({ ...document, fileName })
}

function compareNames(first, second) {
  return first.localeCompare(second, undefined, { numeric: true, sensitivity: 'base' })
}

function renderDirectory(node, depth = 0) {
  const lines = []
  const indentation = '  '.repeat(depth)
  const files = [...node.files].sort((first, second) => {
    if (first.fileName === 'README.md') return -1
    if (second.fileName === 'README.md') return 1
    if (first.fileName === 'index.md') return -1
    if (second.fileName === 'index.md') return 1
    return compareNames(first.fileName, second.fileName)
  })

  for (const document of files) {
    if (depth === 0 && document.fileName === 'index.md') continue
    lines.push(`${indentation}- [${escapeLabel(document.title)}](${document.relativePath})`)
  }

  const directories = [...node.directories.entries()].sort(([first], [second]) =>
    compareNames(first, second),
  )

  for (const [directoryName, directory] of directories) {
    lines.push(`${indentation}- **${escapeLabel(humanize(directoryName))}**`)
    lines.push(...renderDirectory(directory, depth + 1))
  }

  return lines
}

const absoluteFiles = await collectMarkdownFiles(docsRoot)
const documents = await Promise.all(
  absoluteFiles.map(async (absolutePath) => ({
    absolutePath,
    relativePath: path.relative(docsRoot, absolutePath).split(path.sep).join('/'),
    title: await readTitle(absolutePath),
  })),
)

const tree = createDirectoryNode()
for (const document of documents) addToTree(tree, document)

const sidebar = [
  '- [Home](index.md)',
  '',
  ...renderDirectory(tree),
  '',
  `<!-- Generated by tools/docs/generate-pages-navigation.mjs from ${documents.length} Markdown documents. -->`,
  '',
].join('\n')

await fs.writeFile(outputPath, sidebar)
console.log(`Generated docs/_sidebar.md with ${documents.length} documents`)
